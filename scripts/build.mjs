/**
 * Build the two runtime artifacts from src/:
 *   index.js   — ESM Host half (no dependencies)
 *   client.js  — single-file browser module, Chart.js bundled, React provided by the host loader
 *
 * The Client artifact is a CommonJS bundle wrapped in the Harness module-loader call, so
 * `require('react')` resolves to the host's module table while everything else is self-contained.
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const banner = `/* ${pkg.name} v${pkg.version} · SPDX-License-Identifier: MIT · generated by scripts/build.mjs */`

const host = await build({
  entryPoints: [path.join(root, 'src/host/index.js')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'node18',
  write: false,
  legalComments: 'none',
  banner: { js: banner },
})

const client = await build({
  entryPoints: [path.join(root, 'src/client/index.js')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react'],
  write: false,
  minify: true,
  legalComments: 'none',
  banner: { js: banner },
})

const indent = (text) => text.split('\n').map((line) => (line.length > 0 ? `    ${line}` : line)).join('\n')
const clientSource = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
${indent(client.outputFiles[0].text.trimEnd())}
    const exported = module.exports
    return exported && exported.default !== undefined ? exported.default : exported
  },
})
`

await writeFile(path.join(root, 'index.js'), host.outputFiles[0].text)
await writeFile(path.join(root, 'client.js'), clientSource)

const kb = (value) => `${(value / 1024).toFixed(1)} KiB`
console.log(`index.js  ${kb(Buffer.byteLength(host.outputFiles[0].text))}`)
console.log(`client.js ${kb(Buffer.byteLength(clientSource))} (Chart.js bundled, react external)`)
